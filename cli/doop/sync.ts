import { existsSync } from 'node:fs'
import { join } from 'node:path'
import { changedComponents, pullComponents, pushComponents, type SyncPart } from './components.ts'
import type { Context, Outcome } from './context.ts'
import { EXIT, usage } from './errors.ts'
import { changedFrames, pullFrames, pushFrames } from './frames.ts'
import { expandFrame } from './look.ts'
import { PROJECT_DIR, componentBase, projectPath, requireProject, type Project } from './project.ts'

/**
 * `doop pull` and `doop push`: a canvas's components and frames to and from the linked
 * directory. Components go first both ways: a pull learns which frames are their mains, and a
 * push lands a new component before the frame that uses it.
 */

/** The paths named on the command line, as components (by their shared path) and the rest. */
function split(project: Project, context: Context): { components: string[]; others: string[] } {
  const components = new Set<string>()
  const others: string[] = []
  for (const arg of context.args) {
    const base = componentBase(project, projectPath(project, context.cwd, arg))
    if (base) components.add(base)
    else others.push(arg)
  }
  return { components: [...components], others }
}

/** The linked directory, for a command that reads and writes its state. `--canvas` names
 *  another canvas for a one-off look; its frames do not belong in this directory's files. */
function linked(context: Context): Project {
  const project = requireProject(context.project)
  if (context.flags.canvas && context.flags.canvas !== project.config.canvas)
    throw usage(
      'pull and push work on the canvas this directory is linked to',
      'for another canvas, link another directory to it: `doop link <canvas>`',
    )
  return project
}

function outcome(parts: SyncPart[], empty: string, conflictHint: (file: string) => string, next?: string): Outcome {
  const lines = parts.flatMap((part) => part.lines)
  const conflicts = parts.flatMap((part) => part.conflicts)
  const data = { components: parts[0]?.results ?? [], frames: parts[1]?.results ?? [] }
  if (!lines.length) return { text: empty, data }
  const [first] = conflicts
  if (first) return { text: [...lines, '', conflictHint(first)].join('\n'), data, exitCode: EXIT.conflict }
  return { text: [...lines, ...(next ? ['', next] : [])].join('\n'), data }
}

export async function pull(context: Context): Promise<Outcome> {
  const project = linked(context)
  const named = split(project, context)
  const all = !context.args.length
  const components =
    all || named.components.length
      ? await pullComponents(context, project, named.components)
      : { lines: [], results: [], conflicts: [], mainFrameIds: new Set<string>() }
  const frames: SyncPart =
    all || named.others.length
      ? await pullFrames(context, project, named.others, components.mainFrameIds)
      : { lines: [], results: [], conflicts: [] }
  if (context.flags.expand)
    for (const frame of frames.results as { id: string; name: string; file: string }[])
      frames.lines.push(`${'expanded'.padEnd(18)} ${await expandFrame(context, frame)}`)
  return outcome(
    [components, frames],
    context.flags.ready ? 'no frames are marked ready for dev' : 'this canvas has no frames or components yet',
    (file) =>
      existsSync(join(project.root, file))
        ? `conflict: the file and the canvas both changed. \`doop diff\` shows a frame's difference; ` +
          `\`doop pull ${file} --force\` takes the canvas, \`doop push ${file} --force\` takes the file.`
        : `conflict: ${file} is missing, and the component changed both here and on the canvas. ` +
          `\`doop pull ${file} --force\` takes the canvas; to keep yours, put ${file} back first, then ` +
          `\`doop push ${file} --force\`.`,
  )
}

export async function push(context: Context): Promise<Outcome> {
  const project = linked(context)
  const named = split(project, context)
  const files = named.others.map((file) => projectPath(project, context.cwd, file))
  const generated = files.find((file) => file.startsWith(`${PROJECT_DIR}/`))
  if (generated)
    throw usage(
      `${generated} is generated by the CLI and is not pushed`,
      'edit the frame’s own file (`doop frames` shows which one), then push that',
    )
  const all = !context.args.length
  const components = await pushComponents(context, project, all ? changedComponents(project) : named.components)
  const frames = await pushFrames(context, project, all ? changedFrames(project) : files)
  const landed = (frames.results as { outcome: string; file: string }[]).find(
    (entry) => entry.outcome === 'pushed' || entry.outcome === 'created',
  )
  const component = (components.results as { outcome: string; file: string }[]).find(
    (entry) => entry.outcome === 'pushed' || entry.outcome === 'created',
  )
  const seen = landed ?? component
  return outcome(
    [components, frames],
    'nothing to push: no tracked file has changed',
    (file) =>
      `conflict: the canvas changed since the last pull. \`doop pull ${file} --force\` takes the canvas, ` +
      `\`doop push ${file} --force\` takes the file.`,
    seen ? `next: doop screenshot ${seen.file}` : undefined,
  )
}
