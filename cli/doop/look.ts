import { mkdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, extname, join, relative, resolve } from 'node:path'
import { readFrameHtml } from './api.ts'
import { callJson, callTool } from './client.ts'
import { need, numberFlag, type Context, type FrameRef, type Outcome } from './context.ts'
import { CliError, usage } from './errors.ts'
import { trackedComponent } from './components.ts'
import { componentBase, expandedDir, projectPath, shotsDir, slugOf } from './project.ts'

/**
 * Seeing a frame without reading it into the conversation: the bytes go to a file and the
 * command prints the path, so the agent opens the image only when it wants to look.
 */

function save(path: string, data: Buffer | string): void {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, data)
}

function shown(context: Context, path: string): string {
  const local = relative(context.cwd, path)
  return local.startsWith('..') ? path : local
}

/** files this command has written: two frames of one name do not share one */
const taken = new Set<string>()

/** A frame's output file: named after its local file when it has one (pull keeps those
 *  apart), else after its name, with a piece of the id when another frame took that already. */
function fileFor(dir: string, frame: FrameRef, ext: string): string {
  const stem = frame.file ? basename(frame.file).replace(/\.[^.]+$/, '') : slugOf(frame.name)
  const plain = join(dir, `${stem}.${ext}`)
  const path = taken.has(plain) ? join(dir, `${stem}-${frame.id.slice(0, 4).toLowerCase()}.${ext}`) : plain
  taken.add(path)
  return path
}

/** Where a frame's file lands: `--out` as a file (it has an extension) or a directory, else `fallbackDir`. */
function outputPath(context: Context, frame: FrameRef, ext: string, fallbackDir: string, single: boolean): string {
  const out = context.flags.out
  if (!out) return fileFor(fallbackDir, frame, ext)
  const target = resolve(context.cwd, out)
  if (extname(out)) {
    if (!single) throw usage('--out names one file but there are several frames', 'pass a directory instead')
    return target
  }
  return fileFor(target, frame, ext)
}

export async function screenshot(context: Context): Promise<Outcome> {
  const ref = need(context.args[0], 'a frame', 'usage: doop screenshot <frame or file> [-o file.png] [--scale 2]')
  const base = context.project
    ? componentBase(context.project, projectPath(context.project, context.cwd, ref))
    : undefined
  const component = trackedComponent(context.project, base)
  /* a component's file shows its preview: the default instance on a sheet */
  const frame: FrameRef = component ? { id: component.id, name: component.meta.name } : await context.resolveFrame(ref)
  const scale = numberFlag(context.flags.scale, 'scale')
  const result = component
    ? await callTool(context.connection, 'get_component_preview', {
        canvas_id: context.canvasId(),
        component: component.id,
      })
    : await callTool(context.connection, 'get_frame_screenshot', {
        frame_id: frame.id,
        ...(scale ? { scale } : {}),
      })
  context.heard(result)
  const [image] = result.files
  if (!image) throw new CliError('the server sent no image')
  const path = outputPath(context, frame, 'png', context.project ? shotsDir(context.project) : context.cwd, true)
  save(path, image.data)
  return { text: `${shown(context, path)}\n${result.text}`, data: { file: path, caption: result.text } }
}

const GENERATED = (source: string) =>
  `<!-- Generated by \`doop expand\`: the frame as it renders, with its components and tokens written out. Do not edit or push this file: change ${source} and push that. -->`

/** Writes a frame as it renders (component instances in full, component CSS and token values
 *  composed in) to a file a browser can open, and answers its path. The frame's own file keeps
 *  the short form and stays the one that is edited and pushed. */
export async function expandFrame(context: Context, frame: FrameRef): Promise<string> {
  const value = await readFrameHtml(context.connection, frame.id, 'rendered')
  const marker = GENERATED(frame.file ?? `the frame “${frame.name}” on the canvas`)
  /* after the doctype: a comment ahead of it would put the page in quirks mode */
  const doctype = /^\s*<!doctype[^>]*>/i.exec(value.html)?.[0] ?? ''
  const html = `${doctype}${doctype ? '\n' : ''}${marker}\n${value.html.slice(doctype.length)}`
  const path = context.flags.out
    ? outputPath(context, frame, 'html', context.cwd, true)
    : fileFor(context.project ? expandedDir(context.project) : context.cwd, frame, 'html')
  save(path, html)
  return shown(context, path)
}

export async function expand(context: Context): Promise<Outcome> {
  if (!context.args.length) throw usage('missing a frame', 'usage: doop expand <frame or file>… [-o file.html]')
  if (context.args.length > 1 && context.flags.out)
    throw usage('--out names one file but there are several frames', 'expand them one at a time')
  const files: string[] = []
  for (const ref of context.args) files.push(await expandFrame(context, await context.resolveFrame(ref)))
  return {
    text: [...files, 'Generated files: open them to see the page, edit the frame’s own file.'].join('\n'),
    data: { files },
  }
}

interface Inspection {
  problems?: unknown[]
}

export async function inspect(context: Context): Promise<Outcome> {
  const ref = need(context.args[0], 'a frame', 'usage: doop inspect <frame or file> [--selector <css>]…')
  const frame = await context.resolveFrame(ref)
  const { value, result } = await callJson<Inspection>(context.connection, 'inspect_frame', {
    frame_id: frame.id,
    ...(context.flags.selector?.length ? { selectors: context.flags.selector } : {}),
  })
  context.heard(result)
  const problems = value.problems ?? []
  const lines = context.flags.selector?.length
    ? [JSON.stringify(value, null, 2)]
    : [
        problems.length
          ? `${problems.length} possible problem${problems.length === 1 ? '' : 's'} in ${frame.name}:`
          : '',
        ...problems.map((problem) => `- ${JSON.stringify(problem)}`),
        problems.length
          ? 'These are candidates: check them against `doop screenshot`. A deliberate overlap is fine.'
          : `no problems found in ${frame.name}`,
        'The full report (palette, fonts, element boxes) is in --json.',
      ].filter(Boolean)
  return {
    text: lines.join('\n'),
    data: value,
    ...(context.flags['fail-on-problems'] && problems.length ? { exitCode: 1 } : {}),
  }
}

interface ImageExport {
  download_url: string
  width: number
  height: number
}

const EXPORT_FORMATS = ['png', 'jpg', 'pdf']

async function download(url: string): Promise<Buffer> {
  const response = await fetch(url)
  if (!response.ok) throw new CliError(`the export at ${url} answered ${response.status}`)
  return Buffer.from(await response.arrayBuffer())
}

export async function exportFrames(context: Context): Promise<Outcome> {
  const format = context.flags.format ?? 'png'
  if (!EXPORT_FORMATS.includes(format))
    throw usage(`--format is one of ${EXPORT_FORMATS.join(', ')}`, 'other formats: `doop call export_frame`')
  const refs = context.flags.all ? (await context.canvas()).frames.filter((frame) => !frame.hidden) : []
  const targets: FrameRef[] = context.flags.all
    ? refs.map((frame) => ({ id: frame.id, name: frame.name }))
    : await Promise.all(context.args.map((ref) => context.resolveFrame(ref)))
  const [first, ...others] = targets
  if (!first)
    throw usage('missing a frame', 'usage: doop export <frame or file>… [--all] [--format png|jpg|pdf] [-o dir]')

  if (format === 'pdf') {
    /* one document, a page per frame, in the order given */
    const result = await callTool(context.connection, 'export_frame', {
      frame_id: first.id,
      format,
      ...(others.length ? { frame_ids: others.map((frame) => frame.id) } : {}),
    })
    const [file] = result.files
    if (!file) throw new CliError(result.text || 'the server sent no PDF')
    const path = outputPath(context, first, 'pdf', context.cwd, true)
    save(path, file.data)
    return {
      text: `${shown(context, path)}  (${targets.length} page${targets.length === 1 ? '' : 's'})`,
      data: { files: [path] },
    }
  }

  const scale = numberFlag(context.flags.scale, 'scale')
  const quality = numberFlag(context.flags.quality, 'quality')
  const written: { file: string; frame: string; width: number; height: number }[] = []
  for (const frame of targets) {
    const { value } = await callJson<ImageExport>(context.connection, 'export_frame', {
      frame_id: frame.id,
      format,
      ...(scale ? { scale } : {}),
      ...(quality ? { quality } : {}),
    })
    const path = outputPath(context, frame, format, context.cwd, targets.length === 1)
    save(path, await download(value.download_url))
    written.push({ file: path, frame: frame.name, width: value.width, height: value.height })
  }
  return {
    text: written.map((entry) => `${shown(context, entry.file)}  (${entry.width}×${entry.height})`).join('\n'),
    data: { files: written },
  }
}
